"""sync_functions_env.py - write functions-crm/.env from the root .env.

Firebase deploys only functions-crm/.env to the cloud function, so the settings the CRM
function needs are copied there from the single root .env. Runs automatically before every
`firebase deploy --only functions[:crm]` (predeploy hook in firebase.json) and from deploy_crm.sh.
Edit the root .env, never functions-crm/.env. Values are never printed.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
KEYS = ["BATCH_RUNNER_URL", "BATCH_SECRET", "BATCH_SA", "OPENAI_API_KEY", "OPENAI_MODEL"]


def read_root_env() -> dict:
    values = {}
    for line in (ROOT / ".env").read_text(encoding="utf-8").splitlines():
        key, sep, value = line.partition("=")
        if sep and key.strip() in KEYS:
            values[key.strip()] = value.strip().strip("'\"")
    return values


def main() -> None:
    values = read_root_env()
    lines = ["# Auto-generated by sync_functions_env.py - edit the root .env instead"]
    lines += [f"{k}={values[k]}" for k in KEYS if values.get(k)]
    (ROOT / "functions-crm" / ".env").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("functions-crm/.env written with: " + ", ".join(k for k in KEYS if values.get(k)))
    missing = [k for k in KEYS if not values.get(k)]
    if missing:
        print("not set in the root .env (skipped): " + ", ".join(missing))


if __name__ == "__main__":
    main()
